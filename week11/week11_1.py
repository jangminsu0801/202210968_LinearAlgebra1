import numpy as np

A = np.array([
    [2,  3],
    [3, -6]
])

# 1. 특성다항식 계산
coefficients = (-1) ** len(A) * np.poly(A)

print("특성다항식")
print(np.poly1d(np.round(coefficients, 10), variable="λ"))

# 2, 고유값 계산
eigenvalues, eigenvectors = np.linalg.eig(A)

print(f"\n고유값 λ = {eigenvalues[0]:g} , {eigenvalues[1]:g}")