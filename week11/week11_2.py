import numpy as np

A = np.array([
    [3,  2],
    [3, -2]
], dtype=float)

# 고유값과 고유벡터 계산
eigenvalues, X = np.linalg.eig(A)

# 고유값 4, -3 순서대로 정렬
order = np.argsort(eigenvalues)[::-1]
eigenvalues = eigenvalues[order]
X = X[:, order]

# 고유값을 대각행렬로 변환
# MATLAB 화면처럼 정수로 출력되도록 형변환
lamda = np.diag(eigenvalues).astype(int)

np.set_printoptions(precision=4, suppress=True, floatmode="fixed")

print("X =")
print(X)
print("\nlamda =")
print(lamda)