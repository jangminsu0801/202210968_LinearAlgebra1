import numpy as np

# 문제가 두개이므로 대상 행렬과 고유값 출력하는 함수 정의
# 삼각행렬의 주대각선상의 값이 고유값임을 보이기 위해 행렬 또한 출력함
def printEigenval(num, A, eigenvalues):
  print(f"({num})")
  print("A =")
  print(A)
  print("\nλ =", ', '.join(map(str, eigenvalues.astype(int))), "\n")


A1 = np.array([
    [0, 0,  0],
    [0, 2,  5],
    [0, 0, -1]
])

A2 = np.array([
    [4, 0,  0],
    [0, 0,  0],
    [1, 0, -3]
])

# 고유값 계산
eigenvalues1, X1 = np.linalg.eig(A1)
eigenvalues2, X2 = np.linalg.eig(A2)

printEigenval(1, A1, eigenvalues1)
printEigenval(2, A2, eigenvalues2)